(defun %loop-kw-p (x name)
  (and (symbolp x) (not (null x)) (string= (symbol-name x) name)))

(defun %loop-kw-member (x names)
  (and (symbolp x) (not (null x))
       (member (symbol-name x) names :test #'string=)))

(defun %loop-clause-keyword-p (x)
  (%loop-kw-member x
    '("FOR" "AS" "WITH" "WHILE" "UNTIL" "REPEAT"
      "DO" "DOING" "COLLECT" "COLLECTING"
      "APPEND" "APPENDING" "NCONC" "NCONCING"
      "SUM" "SUMMING" "COUNT" "COUNTING"
      "MAXIMIZE" "MAXIMIZING" "MINIMIZE" "MINIMIZING"
      "FINALLY" "INITIALLY" "WHEN" "IF" "UNLESS"
      "ALWAYS" "NEVER" "THEREIS" "NAMED"
      "ELSE" "END" "RETURN")))

(defvar %loop-bindings%)
(defvar %loop-conditions%)
(defvar %loop-presets%)
(defvar %loop-dos%)
(defvar %loop-steps%)
(defvar %loop-initiallys%)
(defvar %loop-finallys%)
(defvar %loop-acc%)
(defvar %loop-acc-kind%)
(defvar %loop-result-kind%)
(defvar %loop-block%)

(defun %loop-bind-pattern (pattern)
  (if (symbolp pattern)
      (when pattern (push (list pattern nil) %loop-bindings%))
      (dolist (p pattern) (%loop-bind-pattern p))))

(defun %loop-assign-pattern (pattern value-form)
  (if (symbolp pattern)
      (if pattern (list `(setq ,pattern ,value-form)) nil)
      (let ((tmp (gensym "D"))
            (forms nil)
            (idx 0))
        (push (list tmp nil) %loop-bindings%)
        (setq forms (list `(setq ,tmp ,value-form)))
        (dolist (p pattern)
          (setq forms (append forms (%loop-assign-pattern p `(nth ,idx ,tmp))))
          (setq idx (1+ idx)))
        forms)))

(defun %loop-acc-target (tail kind init)
  (if (%loop-kw-p (car tail) "INTO")
      (let ((var (cadr tail)))
        (push (list var init) %loop-bindings%)
        (values var (cddr tail)))
      (progn
        (setq %loop-acc-kind% kind)
        (values %loop-acc% tail))))

(defun %loop-parse-body-clause (rest)
  (let ((kw (car rest)))
    (cond
      ((or (%loop-kw-p kw "DO") (%loop-kw-p kw "DOING"))
       (let ((forms nil))
         (setq rest (cdr rest))
         (%while (and (consp rest)
                      (not (%loop-clause-keyword-p (car rest))))
           (push (car rest) forms)
           (setq rest (cdr rest)))
         (values `(progn ,@(reverse forms)) rest)))
      ((or (%loop-kw-p kw "COLLECT") (%loop-kw-p kw "COLLECTING"))
       (let ((expr (cadr rest)))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'collect nil)
           (values `(setq ,var (cons ,expr ,var)) tail))))
      ((or (%loop-kw-p kw "APPEND") (%loop-kw-p kw "APPENDING")
           (%loop-kw-p kw "NCONC") (%loop-kw-p kw "NCONCING"))
       (let ((expr (cadr rest)))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'append nil)
           (values `(setq ,var (append ,var ,expr)) tail))))
      ((or (%loop-kw-p kw "SUM") (%loop-kw-p kw "SUMMING"))
       (let ((expr (cadr rest)))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'sum 0)
           (values `(setq ,var (+ ,var ,expr)) tail))))
      ((or (%loop-kw-p kw "COUNT") (%loop-kw-p kw "COUNTING"))
       (let ((expr (cadr rest)))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'sum 0)
           (values `(when ,expr (setq ,var (1+ ,var))) tail))))
      ((or (%loop-kw-p kw "MAXIMIZE") (%loop-kw-p kw "MAXIMIZING"))
       (let ((expr (cadr rest))
             (v (gensym "V")))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'extremum nil)
           (values `(let ((,v ,expr))
                      (setq ,var (if (null ,var) ,v (max ,var ,v))))
                   tail))))
      ((or (%loop-kw-p kw "MINIMIZE") (%loop-kw-p kw "MINIMIZING"))
       (let ((expr (cadr rest))
             (v (gensym "V")))
         (multiple-value-bind (var tail)
             (%loop-acc-target (cddr rest) 'extremum nil)
           (values `(let ((,v ,expr))
                      (setq ,var (if (null ,var) ,v (min ,var ,v))))
                   tail))))
      ((or (%loop-kw-p kw "WHEN") (%loop-kw-p kw "IF") (%loop-kw-p kw "UNLESS"))
       (let ((test (cadr rest)))
         (multiple-value-bind (form tail)
             (%loop-parse-body-clause (cddr rest))
           (unless form
             (error "loop: ~S must be followed by a body clause" kw))
           (let ((else-form nil))
             (when (%loop-kw-p (car tail) "ELSE")
               (multiple-value-bind (ef et)
                   (%loop-parse-body-clause (cdr tail))
                 (setq else-form ef)
                 (setq tail et)))
             (when (%loop-kw-p (car tail) "END")
               (setq tail (cdr tail)))
             (values (if (%loop-kw-p kw "UNLESS")
                         `(if ,test ,else-form ,form)
                         `(if ,test ,form ,else-form))
                     tail)))))
      ((%loop-kw-p kw "ALWAYS")
       (setq %loop-result-kind% 'boolean)
       (values `(unless ,(cadr rest) (return-from ,%loop-block% nil))
               (cddr rest)))
      ((%loop-kw-p kw "NEVER")
       (setq %loop-result-kind% 'boolean)
       (values `(when ,(cadr rest) (return-from ,%loop-block% nil))
               (cddr rest)))
      ((%loop-kw-p kw "THEREIS")
       (let ((v (gensym "V")))
         (values `(let ((,v ,(cadr rest)))
                    (when ,v (return-from ,%loop-block% ,v)))
                 (cddr rest))))
      (t (values nil nil)))))

(defun %loop-parse-for (rest)
  (let ((var (cadr rest))
        (what (caddr rest)))
    (cond
      ((%loop-kw-member what '("FROM" "DOWNFROM" "UPFROM"))
       (let ((start (nth 3 rest))
             (tail (nthcdr 4 rest))
             (limit-var (gensym "LIMIT"))
             (by-var (gensym "BY"))
             (kind nil)
             (down (%loop-kw-p what "DOWNFROM")))
         (push (list var start) %loop-bindings%)
         (when (%loop-kw-member (car tail)
                                '("TO" "UPTO" "BELOW" "DOWNTO" "ABOVE"))
           (setq kind (symbol-name (car tail)))
           (push (list limit-var (cadr tail)) %loop-bindings%)
           (setq tail (cddr tail)))
         (when (and kind
                    (or (string= kind "DOWNTO") (string= kind "ABOVE")))
           (setq down t))
         (if (%loop-kw-p (car tail) "BY")
             (progn
               (push (list by-var (cadr tail)) %loop-bindings%)
               (setq tail (cddr tail)))
             (push (list by-var 1) %loop-bindings%))
         (when kind
           (cond ((string= kind "BELOW")
                  (push `(< ,var ,limit-var) %loop-conditions%))
                 ((string= kind "ABOVE")
                  (push `(> ,var ,limit-var) %loop-conditions%))
                 ((string= kind "DOWNTO")
                  (push `(>= ,var ,limit-var) %loop-conditions%))
                 (t
                  (push `(<= ,var ,limit-var) %loop-conditions%))))
         (if down
             (push `(setq ,var (- ,var ,by-var)) %loop-steps%)
             (push `(setq ,var (+ ,var ,by-var)) %loop-steps%))
         tail))
      ((%loop-kw-p what "IN")
       (let ((lst (gensym "LST")))
         (push (list lst (nth 3 rest)) %loop-bindings%)
         (%loop-bind-pattern var)
         (push `(consp ,lst) %loop-conditions%)
         (dolist (f (%loop-assign-pattern var `(car ,lst)))
           (push f %loop-presets%))
         (push `(setq ,lst (cdr ,lst)) %loop-steps%)
         (nthcdr 4 rest)))
      ((%loop-kw-p what "ON")
       (let ((lst (gensym "LST")))
         (push (list lst (nth 3 rest)) %loop-bindings%)
         (%loop-bind-pattern var)
         (push `(consp ,lst) %loop-conditions%)
         (dolist (f (%loop-assign-pattern var lst))
           (push f %loop-presets%))
         (push `(setq ,lst (cdr ,lst)) %loop-steps%)
         (nthcdr 4 rest)))
      ((%loop-kw-p what "ACROSS")
       (let ((vec (gensym "VEC"))
             (idx (gensym "IDX")))
         (push (list vec (nth 3 rest)) %loop-bindings%)
         (push (list idx 0) %loop-bindings%)
         (%loop-bind-pattern var)
         (push `(< ,idx (length ,vec)) %loop-conditions%)
         (dolist (f (%loop-assign-pattern var `(elt ,vec ,idx)))
           (push f %loop-presets%))
         (push `(setq ,idx (1+ ,idx)) %loop-steps%)
         (nthcdr 4 rest)))
      ((%loop-kw-p what "=")
       (let ((init (nth 3 rest))
             (tail (nthcdr 4 rest)))
         (%loop-bind-pattern var)
         (if (%loop-kw-p (car tail) "THEN")
             (progn
               (dolist (f (%loop-assign-pattern var init))
                 (push f %loop-initiallys%))
               (dolist (f (%loop-assign-pattern var (cadr tail)))
                 (push f %loop-steps%))
               (cddr tail))
             (progn
               (dolist (f (%loop-assign-pattern var init))
                 (push f %loop-presets%))
               tail))))
      ((%loop-kw-p what "BEING")
       (let ((tail (nthcdr 3 rest)))
         (when (%loop-kw-member (car tail) '("THE" "EACH"))
           (setq tail (cdr tail)))
         (let ((what2 (car tail))
               (pairs (gensym "PAIRS"))
               (keyp nil))
           (cond ((%loop-kw-member what2 '("HASH-KEYS" "HASH-KEY"))
                  (setq keyp t))
                 ((%loop-kw-member what2 '("HASH-VALUES" "HASH-VALUE"))
                  (setq keyp nil))
                 (t (error "loop: unsupported BEING clause ~S" what2)))
           (setq tail (cdr tail))
           (unless (%loop-kw-member (car tail) '("OF" "IN"))
             (error "loop: BEING needs OF"))
           (push (list pairs `(%hash-pairs ,(cadr tail))) %loop-bindings%)
           (push (list var nil) %loop-bindings%)
           (push `(consp ,pairs) %loop-conditions%)
           (push `(setq ,var ,(if keyp
                                  `(car (car ,pairs))
                                  `(cdr (car ,pairs))))
                 %loop-presets%)
           (setq tail (cddr tail))
           (when (%loop-kw-p (car tail) "USING")
             (let ((spec (cadr tail)))
               (push (list (cadr spec) nil) %loop-bindings%)
               (push `(setq ,(cadr spec)
                            ,(if keyp
                                 `(cdr (car ,pairs))
                                 `(car (car ,pairs))))
                     %loop-presets%)
               (setq tail (cddr tail))))
           (push `(setq ,pairs (cdr ,pairs)) %loop-steps%)
           tail)))
      (t (error "loop: unsupported FOR clause near ~S" what)))))

(defun %loop-expand (clauses)
  (let ((%loop-bindings% nil)
        (%loop-conditions% nil)
        (%loop-presets% nil)
        (%loop-dos% nil)
        (%loop-steps% nil)
        (%loop-initiallys% nil)
        (%loop-finallys% nil)
        (%loop-acc% (gensym "ACC"))
        (%loop-acc-kind% nil)
        (%loop-result-kind% nil)
        (%loop-block% nil)
        (rest clauses))
    (when (%loop-kw-p (car rest) "NAMED")
      (setq %loop-block% (cadr rest))
      (setq rest (cddr rest)))
    (%while (consp rest)
      (let ((kw (car rest)))
        (cond
          ((or (%loop-kw-p kw "FOR") (%loop-kw-p kw "AS"))
           (setq rest (%loop-parse-for rest)))
          ((%loop-kw-p kw "WITH")
           (let ((var (cadr rest)))
             (if (%loop-kw-p (caddr rest) "=")
                 (progn
                   (push (list var (nth 3 rest)) %loop-bindings%)
                   (setq rest (nthcdr 4 rest)))
                 (progn
                   (push (list var nil) %loop-bindings%)
                   (setq rest (cddr rest))))
             (%while (%loop-kw-p (car rest) "AND")
               (let ((var2 (cadr rest)))
                 (if (%loop-kw-p (caddr rest) "=")
                     (progn
                       (push (list var2 (nth 3 rest)) %loop-bindings%)
                       (setq rest (nthcdr 4 rest)))
                     (progn
                       (push (list var2 nil) %loop-bindings%)
                       (setq rest (cddr rest))))))))
          ((%loop-kw-p kw "REPEAT")
           (let ((counter (gensym "COUNT"))
                 (limit (gensym "LIMIT")))
             (push (list limit (cadr rest)) %loop-bindings%)
             (push (list counter 0) %loop-bindings%)
             (push `(< ,counter ,limit) %loop-conditions%)
             (push `(setq ,counter (1+ ,counter)) %loop-steps%)
             (setq rest (cddr rest))))
          ((%loop-kw-p kw "WHILE")
           (push (cadr rest) %loop-conditions%)
           (setq rest (cddr rest)))
          ((%loop-kw-p kw "UNTIL")
           (push `(not ,(cadr rest)) %loop-conditions%)
           (setq rest (cddr rest)))
          ((%loop-kw-p kw "INITIALLY")
           (setq rest (cdr rest))
           (%while (and (consp rest)
                        (not (%loop-clause-keyword-p (car rest))))
             (push (car rest) %loop-initiallys%)
             (setq rest (cdr rest))))
          ((%loop-kw-p kw "FINALLY")
           (setq rest (cdr rest))
           (when (%loop-kw-p (car rest) "RETURN")
             (push `(return-from ,%loop-block% ,(cadr rest)) %loop-finallys%)
             (setq rest (cddr rest)))
           (%while (and (consp rest)
                        (not (%loop-clause-keyword-p (car rest))))
             (push (car rest) %loop-finallys%)
             (setq rest (cdr rest))))
          ((%loop-kw-p kw "RETURN")
           (push `(return-from ,%loop-block% ,(cadr rest)) %loop-dos%)
           (setq rest (cddr rest)))
          (t
           (multiple-value-bind (form tail) (%loop-parse-body-clause rest)
             (if form
                 (progn
                   (push form %loop-dos%)
                   (setq rest tail))
                 (error "loop: unsupported clause ~S" kw)))))))
    (let ((acc-init (case %loop-acc-kind%
                      ((sum) 0)
                      (otherwise nil)))
          (result (cond ((eq %loop-result-kind% 'boolean) t)
                        ((eq %loop-acc-kind% 'collect) `(reverse ,%loop-acc%))
                        ((member %loop-acc-kind% '(append sum extremum))
                         %loop-acc%)
                        (t nil))))
      `(block ,%loop-block%
         (let* (,@(reverse %loop-bindings%)
                (,%loop-acc% ,acc-init))
           ,@(reverse %loop-initiallys%)
           (%while ,(if %loop-conditions%
                        `(and ,@(reverse %loop-conditions%))
                        t)
             ,@(reverse %loop-presets%)
             ,@(reverse %loop-dos%)
             ,@(reverse %loop-steps%))
           ,@(reverse %loop-finallys%)
           ,result)))))

(defmacro loop (&rest clauses)
  (if (or (null clauses)
          (not (%loop-clause-keyword-p (car clauses))))
      `(block nil (%while t ,@clauses))
      (%loop-expand clauses)))

(defmacro loop-finish ()
