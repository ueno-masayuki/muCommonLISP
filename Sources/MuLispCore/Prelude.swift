(defmacro with-accessors (specs instance &rest body)
  (let ((obj (gensym "OBJ")))
    `(let ((,obj ,instance))
       (symbol-macrolet
           ,(mapcar (lambda (s)
                      (list (car s) (list (cadr s) obj)))
                    specs)
         ,@body))))

(defmacro handler-case (form &rest clauses)
  (let ((cv (gensym "C")))
    `(%handler-case
      (lambda () ,form)
      (list ,@(mapcar
               (lambda (clause)
                 (let ((type (car clause))
                       (var-list (cadr clause))
                       (body (cddr clause)))
                   `(list ',type
                          (lambda (,cv)
                            ,(if (consp var-list)
                                 `(let ((,(car var-list) ,cv)) ,@body)
                                 `(progn ,@body))))))
               clauses)))))

